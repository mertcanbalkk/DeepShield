"""DeepShield: fine-tune an EfficientNet-B0 binary full-image AI-origin detector.

Input must be labeled folders (train/val/test)/(ai/real). No training examples
are generated by this script. Train-test contamination is explicitly checked.
Example: python training/train_classifier.py --data datasets/ai_origin --epochs 8
"""
from __future__ import annotations

import argparse
from collections import Counter
from hashlib import sha256
import json
from pathlib import Path
import random
from io import BytesIO
from PIL import Image, ImageFilter

try:
    from .decision import tune_thresholds
    from .dataset_quality import audit
except ImportError:  # python training/train_classifier.py
    from decision import tune_thresholds
    from dataset_quality import audit

IMAGE_SUFFIXES = {'.jpg', '.jpeg', '.png', '.webp', '.tif', '.tiff'}
CLASSES = ('ai', 'real')


class RandomRealWorldDegradation:
    """Apply label-preserving recompression/resizing, not just clean training crops."""
    def __call__(self, image):
        image = image.convert("RGB")
        if random.random() < .55:
            buf = BytesIO()
            image.save(buf, "JPEG", quality=random.randint(45, 95))
            buf.seek(0)
            with Image.open(buf) as im:
                image = im.convert("RGB")
        if random.random() < .30:
            w,h = image.size
            factor = random.uniform(.55, .9)
            image = image.resize((max(24,int(w*factor)),max(24,int(h*factor))), Image.Resampling.BICUBIC)
        if random.random() < .15:
            image = image.filter(ImageFilter.GaussianBlur(radius=random.uniform(.15,.8)))
        return image

def scan_dataset(root: Path) -> dict:
    """Pure standard-library validation; safe before installing pytorch."""
    counts, hashes, duplicated = {}, {}, []
    for split in ('train', 'val', 'test'):
        for label in CLASSES:
            folder = root / split / label
            if not folder.is_dir():
                raise ValueError(f'Klasör bulunamadı: {folder}')
            paths = sorted(p for p in folder.rglob('*') if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES)
            if not paths:
                raise ValueError(f'Etiketli görsel yok: {folder}')
            counts[f'{split}/{label}'] = len(paths)
            for path in paths:
                digest = sha256(path.read_bytes()).hexdigest()
                if digest in hashes and hashes[digest][0] != split:
                    duplicated.append((str(path), hashes[digest][1]))
                hashes.setdefault(digest, (split, str(path)))
    if duplicated:
        raise ValueError('Eğitim/doğrulama/test arasında birebir tekrarlanan dosya var: ' + str(duplicated[:3]))
    return counts


def set_seed(seed: int):
    import numpy as np
    import torch
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def model_and_transforms(pretrained: bool):
    import torch
    from torchvision import transforms, models

    weights = models.EfficientNet_B0_Weights.DEFAULT if pretrained else None
    model = models.efficientnet_b0(weights=weights)
    model.classifier[1] = torch.nn.Linear(model.classifier[1].in_features, 2)
    # No random horizontal flips: physical camera clues can be orientation dependent.
    normalize = transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    train_tf = transforms.Compose([
        RandomRealWorldDegradation(),
        transforms.RandomResizedCrop(224, scale=(.8,1.0), ratio=(.85,1.15)),
        transforms.ToTensor(), normalize,
    ])
    eval_tf = transforms.Compose([
        transforms.Resize(256), transforms.CenterCrop(224), transforms.ToTensor(), normalize,
    ])
    return model, train_tf, eval_tf


def metrics_from_counts(tp: int, fp: int, fn: int, tn: int) -> dict[str, float]:
    safe = lambda n, d: n / d if d else 0.0
    precision = safe(tp, tp + fp)
    recall = safe(tp, tp + fn)
    return {'accuracy': safe(tp + tn, tp + fp + fn + tn),
            'precision_ai': precision, 'recall_ai': recall,
            'f1_ai': safe(2 * precision * recall, precision + recall),
            'false_positive_rate': safe(fp, fp + tn),
            'confusion': {'tp_ai':tp,'fp_ai':fp,'fn_ai':fn,'tn_ai':tn}}


def evaluate(model, dataloader, device):
    import torch
    model.eval()
    total_loss = 0.
    counts = Counter()
    ce = torch.nn.CrossEntropyLoss()
    with torch.inference_mode():
        for x, y in dataloader:
            x, y = x.to(device), y.to(device)
            scores = model(x)
            total_loss += float(ce(scores, y).item()) * y.shape[0]
            pred = scores.argmax(dim=1)
            # class 0=ai is our positive class
            counts['tp'] += int(((pred == 0) & (y == 0)).sum())
            counts['fp'] += int(((pred == 0) & (y == 1)).sum())
            counts['fn'] += int(((pred == 1) & (y == 0)).sum())
            counts['tn'] += int(((pred == 1) & (y == 1)).sum())
    m = metrics_from_counts(counts['tp'], counts['fp'], counts['fn'], counts['tn'])
    m['loss'] = total_loss / max(1, sum(counts.values()))
    return m


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--data', type=Path, required=True, help='train/val/test altında ai/real klasörleri')
    parser.add_argument('--out', type=Path, default=Path('outputs/deepshield_ai_b0.pt'))
    parser.add_argument('--epochs', type=int, default=8)
    parser.add_argument('--batch-size', type=int, default=16)
    parser.add_argument('--lr', type=float, default=1e-4)
    parser.add_argument('--seed', type=int, default=42)
    parser.add_argument('--num-workers', type=int, default=0)
    parser.add_argument('--no-pretrained', action='store_true')
    parser.add_argument('--max-val-error', type=float, default=.05, help='Doğrulama kümesinde hedef yanlış alarm sınırı')
    parser.add_argument('--skip-near-duplicate-audit', action='store_true', help='Yalnızca manuel kontrol sonrası kullanın')
    args = parser.parse_args()
    if args.epochs < 1 or args.batch_size < 1:
        parser.error('Epoch ve batch-size pozitif olmalı.')
    counts = scan_dataset(args.data)
    print('Veri dağılımı:', counts)
    if not args.skip_near_duplicate_audit:
        quality = audit(args.data)
        if not quality['valid']:
            raise ValueError('Veri kümesinde olası aynı/benzer görsel sızıntısı veya bozuk dosya var: '
                             + json.dumps({'duplicates':quality['collisions'][:5], 'invalid':quality['invalid'][:5]}, ensure_ascii=False))
    import torch
    from torchvision.datasets import ImageFolder
    from torch.utils.data import DataLoader
    set_seed(args.seed)
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model, train_tf, eval_tf = model_and_transforms(not args.no_pretrained)
    datasets = {split: ImageFolder(str(args.data / split), transform=train_tf if split == 'train' else eval_tf)
                for split in ('train','val','test')}
    for split, dataset in datasets.items():
        if dataset.class_to_idx != {'ai':0, 'real':1}:
            raise ValueError(f'Yanlış sınıf sırası: {split} {dataset.class_to_idx}')
    loaders = {key: DataLoader(ds, batch_size=args.batch_size, shuffle=(key=='train'),
                                num_workers=args.num_workers) for key, ds in datasets.items()}
    model.to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-3)
    loss_fn = torch.nn.CrossEntropyLoss()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    best_f1 = -1.0
    for epoch in range(1, args.epochs+1):
        model.train()
        running = 0.0
        for x, y in loaders['train']:
            x, y = x.to(device), y.to(device)
            optimizer.zero_grad(set_to_none=True)
            loss = loss_fn(model(x), y)
            loss.backward()
            optimizer.step()
            running += float(loss.detach())*len(y)
        val = evaluate(model, loaders['val'], device)
        print(f'Epoch {epoch}/{args.epochs} loss={running/len(datasets["train"]):.4f} val={json.dumps(val)}')
        if val['f1_ai'] > best_f1:
            best_f1 = val['f1_ai']
            torch.save({'model_state': model.state_dict(), 'classes': ['ai','real'],
                        'architecture':'efficientnet_b0', 'image_size': 224,
                        'mean':[0.485,0.456,0.406], 'std':[0.229,0.224,0.225],
                        'training_counts':counts, 'val_metrics':val}, args.out)
    # Calibrate on validation only, AFTER checkpoint selection. Test stays untouched.
    checkpoint = torch.load(args.out, map_location=device, weights_only=True)
    model.load_state_dict(checkpoint['model_state'])
    model.eval()
    val_scores, val_labels = [], []
    with torch.inference_mode():
        for x, y in loaders['val']:
            pred = torch.softmax(model(x.to(device)), dim=1)[:,0].cpu().tolist()
            val_scores.extend(pred)
            val_labels.extend(y.tolist())
    calibrated = tune_thresholds(val_scores, val_labels, max_error=args.max_val_error)
    checkpoint['calibration'] = calibrated
    torch.save(checkpoint, args.out)
    print('Doğrulama tabanlı karar eşikleri:', json.dumps(calibrated, ensure_ascii=False))
    # Load best checkpoint before final test; test set not used for model selection.
    checkpoint = torch.load(args.out, map_location=device, weights_only=True)
    model.load_state_dict(checkpoint['model_state'])
    final = evaluate(model, loaders['test'], device)
    metrics_path = args.out.with_suffix('.metrics.json')
    metrics_path.write_text(json.dumps({'test_metrics':final, 'val_best_f1':best_f1,
                                        'counts':counts, 'validation_calibration':calibrated, 'warning':'Test in-distribution only; run an independent producer-held-out evaluation.'}, indent=2),encoding='utf-8')
    print('Test metrics:', json.dumps(final))
    print('Model:', args.out, 'Rapor:', metrics_path)


if __name__ == '__main__':
    main()
